"""
gen_font.py - bake the on-screen control labels' font into main/font_data.c

Renders printable ASCII (U+0020-U+007E) into a 10 x 20 cell with 4-bit
anti-aliasing (16 alpha levels, 2 pixels per byte).

Usage:  python3 tools/gen_font.py [--font path/to/DejaVuSansMono-Bold.ttf] [--preview out.png]
Font:   DejaVu Sans Mono Bold (Bitstream Vera license, see main/FONT_LICENSE.txt).
Needs:  pip install pillow
"""
import argparse, os, sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIRS = ["/usr/share/fonts/truetype/dejavu", "/Library/Fonts", "C:/Windows/Fonts",
             os.path.expanduser("~/.fonts"), os.path.expanduser("~/Library/Fonts")]
FONT = "DejaVuSansMono-Bold.ttf"
CW, CH = 10, 20


def find(name):
    for d in FONT_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    return None


def render(path, cps):
    f = ImageFont.truetype(path, CW / 0.6021)   # DejaVu Sans Mono advance = 0.6021 em
    baseline = round(CH * 0.76)
    glyphs = []
    for cp in cps:
        img = Image.new("L", (CW * 3, CH * 2), 0)
        ImageDraw.Draw(img).text((CW, baseline + CH // 2), chr(cp), font=f, fill=255, anchor="ls")
        g = img.crop((CW, CH // 2, CW * 2, CH // 2 + CH))
        nib = [min(15, (v + 8) // 17) for v in g.tobytes()]
        packed = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((cp, packed, g))
    return glyphs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=None, help=f"path to {FONT} (searched for if omitted)")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "main", "font_data.c"))
    ap.add_argument("--preview", default=None)
    a = ap.parse_args()

    path = a.font or find(FONT)
    if not path:
        sys.exit(f"{FONT} not found - pass --font")
    glyphs = render(path, range(0x20, 0x7F))
    tag = f"{CW}x{CH}"

    with open(a.out, "w", encoding="utf-8") as o:
        o.write("// Generated by tools/gen_font.py - do not edit by hand.\n")
        o.write("// 4bpp alpha, high nibble = first pixel.\n")
        o.write("// Glyph art: DejaVu Sans Mono Bold (Bitstream Vera license, see FONT_LICENSE.txt).\n")
        o.write('#include "font.h"\n\n')
        o.write(f"static const uint16_t cps_{tag}[] = {{\n")
        for i in range(0, len(glyphs), 12):
            o.write("    " + ", ".join(f"0x{g[0]:04X}" for g in glyphs[i:i + 12]) + ",\n")
        o.write("};\n")
        o.write(f"static const uint8_t bmp_{tag}[] = {{\n")
        for cp, packed, _ in glyphs:
            o.write(f"    // U+{cp:04X}\n")
            for i in range(0, len(packed), 25):
                o.write("    " + ",".join(f"0x{b:02X}" for b in packed[i:i + 25]) + ",\n")
        o.write("};\n")
        o.write(f"const font_t font_{tag} = {{ {CW}, {CH}, {len(glyphs)}, {(CW * CH + 1) // 2}, cps_{tag}, bmp_{tag} }};\n")
    print(f"{tag}: {len(glyphs)} glyphs, wrote {a.out}")

    if a.preview:
        cols = 32
        rows = (len(glyphs) + cols - 1) // cols
        sheet = Image.new("L", (cols * CW * 3, rows * CH * 3), 20)
        for i, (_, _, g) in enumerate(glyphs):
            sheet.paste(g.resize((CW * 3, CH * 3), Image.NEAREST), ((i % cols) * CW * 3, (i // cols) * CH * 3))
        sheet.save(a.preview)


if __name__ == "__main__":
    main()
